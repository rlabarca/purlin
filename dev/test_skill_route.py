"""What the route skill, `skills/route/SKILL.md`, must say.

One test per proof of `specs/skills/skill_route.md`. A copy of the skill with
one name taken out is read through `copy_without`; the file on disk is never
touched.
"""

import re

import skill_checks
from skill_checks import (copy_without, flat, must_name, sentences_with,
                          skill_path, under_heading)

SKILL = skill_path('route')
COMMANDS = ('purlin:route', 'purlin:route on', 'purlin:route off')
FORMAT = 'references/formats/routing_format.md'


def part(name):
    return flat(under_heading(skill_checks.read(SKILL), name))


def split(text):
    return re.split(r'(?<=\.)\s+(?=[A-Z`*0-9])', text)


def with_all(text, names):
    return [s for s in split(text) if all(name in s for name in names)]


# purlin: skill_route PROOF-1
def test_the_route_skill_names_its_commands_and_the_format():
    assert must_name('route', COMMANDS, (FORMAT,)) == []


# purlin: skill_route PROOF-2
def test_a_copy_without_route_off_is_reported():
    with copy_without(SKILL, 'purlin:route off'):
        assert must_name('route', COMMANDS, (FORMAT,)) == [
            'route does not name purlin:route off']


# purlin: skill_route PROOF-3
def test_the_route_skill_names_no_script():
    assert [line for line in skill_checks.read(SKILL).splitlines()
            if re.search(r'scripts/\w', line)] == []


ASK = ('Stop and ask', 'the model each tier gets')
WRITE = 'Write `.purlin/routing.json`'


# purlin: skill_route PROOF-4
def test_setup_asks_for_the_models_before_it_writes_the_file():
    sentences = split(part('On'))
    asked = [n for n, s in enumerate(sentences) if all(a in s for a in ASK)]
    written = [n for n, s in enumerate(sentences) if WRITE in s]
    assert asked and written and asked[0] < written[0]


# purlin: skill_route PROOF-5
def test_a_copy_without_stop_and_ask_asks_nothing():
    with copy_without(SKILL, 'Stop and ask'):
        assert with_all(part('On'), ASK) == []


LOCAL = ('.purlin/routing.local.json', '`tiers` alone', 'git ignores')


# purlin: skill_route PROOF-6
def test_the_local_file_holds_tiers_alone_and_git_ignores_it():
    assert sentences_with(SKILL, LOCAL)


# purlin: skill_route PROOF-7
def test_a_copy_without_git_ignores_holds_no_such_sentence():
    with copy_without(SKILL, 'git ignores'):
        assert sentences_with(SKILL, LOCAL) == []


SETTINGS = ('"agent": "purlin:purlin"', '.claude/settings.json',
            'every other setting')


# purlin: skill_route PROOF-8
def test_setup_writes_the_session_settings_and_off_takes_them_out():
    assert with_all(part('On'), SETTINGS)
    assert with_all(part('Off'), ('.claude/settings.json', 'takes out'))


# purlin: skill_route PROOF-9
def test_a_copy_without_every_other_setting_holds_no_such_sentence():
    with copy_without(SKILL, 'every other setting'):
        assert with_all(part('On'), SETTINGS) == []


COMMIT = ('.purlin/routing.json', '.claude/settings.json', '.claude/skills/',
          'chore:')


# purlin: skill_route PROOF-10
def test_setup_and_off_each_commit_the_routing_settings_and_skills_under_chore():
    assert with_all(part('On'), COMMIT)
    assert with_all(part('Off'), COMMIT)


# purlin: skill_route PROOF-11
def test_a_copy_without_chore_commits_in_neither_part():
    with copy_without(SKILL, 'chore:'):
        assert with_all(part('On'), COMMIT) == []
        assert with_all(part('Off'), COMMIT) == []


# purlin: skill_route PROOF-12
def test_setup_starts_no_model():
    assert sentences_with(SKILL, ('starts no model',
                                  'fails at the first skill'))


# purlin: skill_route PROOF-13
def test_setup_writes_the_project_skills_and_never_over_another_file():
    assert with_all(part('On'), ('.claude/skills/<skill>/SKILL.md',
                                    '"The project skills"'))
    assert with_all(part('On'), ('Generated by purlin:route',
                                    'never writes over'))


# purlin: skill_route PROOF-14
def test_off_removes_the_project_skills_it_wrote():
    assert with_all(part('Off'), ('.claude/skills/',
                                  'Generated by purlin:route', 'removes'))


# purlin: skill_route PROOF-15
def test_the_gotchas_name_the_four_facts():
    gotchas = part('Gotchas')
    for name in ('Stop and ask', '/purlin:<skill>', 'plain words', 'keeps its own'):
        assert name in gotchas, name


# purlin: skill_route PROOF-16
def test_setup_tells_the_person_which_commands_carry_the_model():
    assert with_all(part('On'), ('/<skill>', 'not /purlin:<skill>', 'plain words'))


def setup_steps():
    """The numbered steps of the part `On`, each as one flat string."""
    text = under_heading(skill_checks.read(SKILL), 'On')
    return [flat(step) for step in re.split(r'\n(?=\d+\. )', text) if re.match(r'\d+\. ', step)]


def first_step(steps, names):
    return next((n for n, step in enumerate(steps) if all(name in step for name in names)), None)


# purlin: skill_route PROOF-17
def test_setup_names_each_part_of_the_format_at_its_step():
    steps = setup_steps()
    tables = first_step(steps, ('"The two tables"',))
    the_file = first_step(steps, ('"The file"',))
    skills = first_step(steps, ('"The project skills"', '"The hand-off message"'))
    assert None not in (tables, the_file, skills) and tables < the_file < skills


# purlin: skill_route PROOF-18
def test_setup_copies_the_templates_exactly():
    assert with_all(part('On'), ('exactly', '<skill>', '<tier>', '<model>'))
    assert with_all(part('On'), ('no `<`', 'placeholder'))


# purlin: skill_route PROOF-19
def test_setup_opens_on_a_checklist_from_the_answer_to_the_commit():
    text = under_heading(skill_checks.read(SKILL), 'On')
    before = text[:re.search(r'^\d+\. ', text, re.M).start()]
    items = [line for line in before.splitlines() if line.startswith('- [ ]')]
    assert items and 'answered' in items[0] and 'Committed' in items[-1]


# purlin: skill_route PROOF-20
def test_setup_checks_its_work_before_it_commits():
    steps = setup_steps()
    check = first_step(steps, ('before you commit', 'model', 'init', '.claude/settings.json', 'again'))
    commit = first_step(steps, ('chore: model routing',))
    assert check is not None and commit is not None and check < commit
